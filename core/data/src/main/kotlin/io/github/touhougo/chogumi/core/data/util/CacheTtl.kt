package io.github.touhougo.chogumi.core.data.util

/**
 * 缓存新鲜度（TTL）策略常量。
 *
 * 核心设计目标：省流量、减请求、弱网保秒开体验。
 * 在 TTL 内有缓存直出、不打网络；过期后进入 SWR 静默刷新。
 */
object CacheTtl {
    /** 每日放送：半天级排期微调（12 小时） */
    const val CALENDAR = 12 * 60 * 60 * 1000L

    /** 用户资料：兼顾网页端编辑与统计变动（10 分钟） */
    const val USER_PROFILE = 10 * 60 * 1000L

    /** 条目详情及其关联条目、角色、制作人员：元数据相对静态（24 小时） */
    const val SUBJECT_DETAIL = 24 * 60 * 60 * 1000L

    /** 章节列表：连载周更，24 小时足以及时发现新分集（24 小时） */
    const val EPISODES = 24 * 60 * 60 * 1000L

    /**
     * 首页进度区块：端点慢且大（实测 2.5-3.4s / 663 KB，
     * 2026-09-29 实测），且当天内进度变化不频繁，
     * 取 10 分钟平衡新鲜度与流量（与用户资料同档）。
     */
    const val HOME_PROGRESS = 10 * 60 * 1000L

    /**
     * 搜索第一页（探索页货架）：热度、排名这类列表小时级才变；30 分钟内再进探索页直接用上次的结果，
     * 不发请求，下拉刷新照常强刷（设计决定，not in M3）。
     */
    const val SEARCH_FIRST_PAGE = 30 * 60 * 1000L

    /**
     * 本人某类收藏的全部页（进度页、个人页书架、首页「也在进行」）：本机的改动直接写进本地，过期只为接上网页端
     * 或别的设备上的改动；重度账号一类就是几十个请求，10 分钟内重进不再取（设计决定）。
     */
    const val USER_COLLECTIONS = 10 * 60 * 1000L

    /** 默认值：无穷大（有缓存直出、不主动网络刷新，保持现状行为） */
    const val INFINITE = Long.MAX_VALUE
}
